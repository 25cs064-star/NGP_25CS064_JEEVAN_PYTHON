# if...else
a = 300
b = 300

if a > b:
    print("A is greater than B")
else:
    print("B is greater than A")

# if...elif...else
if a > b:
    print("A is greater than B")
elif b > a:
    print("B is greater than A")
elif a == b:
    print("Both values are equal")

# Logical Operator in if
if (30 > 20 and 20 > 30):
    print("Hello")

# for Loop
for c in range(5):
    print(c)

# for...else
for x in range(5):
    print(x)
else:
    print("Welcome")